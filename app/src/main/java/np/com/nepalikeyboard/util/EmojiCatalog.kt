    /** Flat catalog used by the search field. Built once, never mutated. */
    val all: List<EmojiEntry> = byCategory.values.flatten()

    /**
     * Keyword search. Case-insensitive substring match over the keyword blob,
     * which contains English and Nepali terms, so "माया", "love" and "heart" all
     * find ❤️. Returns at most [limit] entries.
     */
    fun search(query: String, limit: Int = 60): List<EmojiEntry> {
        val trimmed = query.trim().lowercase()
        if (trimmed.isEmpty()) return emptyList()
        val result = ArrayList<EmojiEntry>(limit)
        for (entry in all) {
            if (entry.keywords.contains(trimmed) || entry.emoji == trimmed) {
                result += entry
                if (result.size >= limit) break
            }
        }
        return result
    }

    fun entriesFor(category: EmojiCategory): List<EmojiEntry> =
        byCategory[category] ?: emptyList()
