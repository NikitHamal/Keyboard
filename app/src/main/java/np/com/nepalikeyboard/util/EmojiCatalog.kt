package np.com.nepalikeyboard.util

import androidx.compose.runtime.Immutable

/** Emoji panel categories, in tab order. */
enum class EmojiCategory(val labelResHint: String) {
    RECENT("Recent"),
    SMILEYS("Smileys"),
    PEOPLE("People"),
    ANIMALS("Animals"),
    FOOD("Food"),
    TRAVEL("Travel"),
    ACTIVITIES("Activities"),
    OBJECTS("Objects"),
    SYMBOLS("Symbols"),
    FLAGS("Flags"),
}

/**
 * One emoji with its search keywords.
 *
 * Keywords intentionally contain both English and Nepali terms so that search
 * works whichever language the user thinks in ("माया" and "love" both find ❤️).
 * The catalog is compiled into the APK, parses nothing at startup and needs no
 * assets: the whole table is ~400 entries and about 20 KB of DEX.
 */
