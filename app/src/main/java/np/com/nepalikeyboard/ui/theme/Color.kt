/**
 * Palette definitions.
 *
 * Material 3 "Expressive" treats containers as tonal steps of a single seed.
 * Rather than shipping hundreds of hard-coded hex values, every palette below
 * declares a small, curated set of *anchors* (primary / secondary / tertiary /
 * accent and the surface pair) and [schemeFrom] derives the remaining ~20 M3
 * roles from them with deterministic tonal interpolation. That keeps the eight
 * generated schemes internally consistent and makes adding a palette a
 * five-line change.
 */
@Immutable
internal data class PaletteAnchors(
    val primary: Color,
    val primaryContainer: Color,
    val secondary: Color,
    val secondaryContainer: Color,
    val tertiary: Color,
    val tertiaryContainer: Color,
    val accent: Color,
    val surfaceLight: Color,
    val surfaceDark: Color,
    val onPrimaryLight: Color = Color.White,
    val onPrimaryDark: Color = Color(0xFF161022),
    val onContainerLight: Color = Color(0xFF1B1030),
    val onContainerDark: Color = Color(0xFFEDE3FF),
)

