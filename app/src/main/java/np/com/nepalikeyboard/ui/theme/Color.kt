// ---------------------------------------------------------------------------
// Derivation
// ---------------------------------------------------------------------------

private const val BLACK_TONE = 0f
private const val WHITE_TONE = 1f

/**
 * Builds a complete [ColorScheme] from [PaletteAnchors].
 *
 * The surface-container ladder is generated by interpolating the palette
 * surface towards its primary/secondary containers, which is what makes the
 * keyboard's tonal elevation read as one family in both light and dark mode.
 */
internal fun schemeFrom(anchors: PaletteAnchors, dark: Boolean): ColorScheme {
    val surface = if (dark) anchors.surfaceDark else anchors.surfaceLight
    val onSurface = if (dark) Color(0xFFE7E1EA) else Color(0xFF1B1B1F)
    val onSurfaceVariant = if (dark) Color(0xFFC9C4D0) else Color(0xFF48454E)
    val blendTint = if (dark) anchors.primary else anchors.secondary

    // The tonal ladder: lowest = furthest from the wallpaper tone.
    val lowest = lerp(surface, if (dark) Color.Black else Color.White, if (dark) 0.35f else 0.55f)
    val low = lerp(surface, blendTint, if (dark) 0.04f else 0.03f)
    val container = lerp(surface, blendTint, if (dark) 0.09f else 0.06f)
    val containerHigh = lerp(surface, blendTint, if (dark) 0.14f else 0.10f)
    val containerHighest = lerp(surface, blendTint, if (dark) 0.19f else 0.14f)
    val bright = lerp(surface, if (dark) Color.White else Color.White, if (dark) 0.06f else 0f)

    val primary = if (dark) lighten(anchors.primary, 0.22f) else anchors.primary
    val primaryContainer = if (dark) darken(anchors.primary, 0.42f) else anchors.primaryContainer
    val secondary = if (dark) lighten(anchors.secondary, 0.24f) else anchors.secondary
    val secondaryContainer = if (dark) darken(anchors.secondary, 0.40f) else anchors.secondaryContainer
    val tertiary = if (dark) lighten(anchors.tertiary, 0.24f) else anchors.tertiary
    val tertiaryContainer = if (dark) darken(anchors.tertiary, 0.40f) else anchors.tertiaryContainer

    val onPrimary = if (dark) anchors.onPrimaryDark else anchors.onPrimaryLight
    val onPrimaryContainer = if (dark) anchors.onContainerDark else anchors.onContainerLight
    val error = if (dark) Color(0xFFFFB4AB) else Color(0xFFBA1A1A)
    val errorContainer = if (dark) Color(0xFF93000A) else Color(0xFFFFDAD6)

    val base = if (dark) {
        darkColorScheme(
            primary = primary,
            onPrimary = onPrimary,
            primaryContainer = primaryContainer,
            onPrimaryContainer = onPrimaryContainer,
            inversePrimary = darken(primary, 0.25f),
            secondary = secondary,
            onSecondary = onPrimary,
            secondaryContainer = secondaryContainer,
            onSecondaryContainer = onPrimaryContainer,
            tertiary = tertiary,
            onTertiary = onPrimary,
            tertiaryContainer = tertiaryContainer,
            onTertiaryContainer = onPrimaryContainer,
            error = error,
            onError = Color(0xFF690005),
            errorContainer = errorContainer,
            onErrorContainer = Color(0xFFFFDAD6),
            background = surface,
            onBackground = onSurface,
            surface = surface,
            onSurface = onSurface,
            surfaceVariant = containerHighest,
            onSurfaceVariant = onSurfaceVariant,
            surfaceTint = primary,
            inverseSurface = onSurface,
            inverseOnSurface = surface,
            outline = lerp(onSurfaceVariant, surface, 0.35f),
            outlineVariant = lerp(onSurfaceVariant, surface, 0.72f),
            scrim = Color.Black,
            surfaceBright = bright,
            surfaceDim = lowest,
            surfaceContainerLowest = lowest,
            surfaceContainerLow = low,
            surfaceContainer = container,
            surfaceContainerHigh = containerHigh,
            surfaceContainerHighest = containerHighest,
        )
    } else {
        lightColorScheme(
            primary = primary,
            onPrimary = onPrimary,
            primaryContainer = primaryContainer,
            onPrimaryContainer = onPrimaryContainer,
            inversePrimary = lighten(primary, 0.35f),
            secondary = secondary,
            onSecondary = onPrimary,
            secondaryContainer = secondaryContainer,
            onSecondaryContainer = onPrimaryContainer,
            tertiary = tertiary,
            onTertiary = onPrimary,
            tertiaryContainer = tertiaryContainer,
            onTertiaryContainer = onPrimaryContainer,
            error = error,
            onError = Color.White,
            errorContainer = errorContainer,
            onErrorContainer = Color(0xFF410E0B),
            background = surface,
            onBackground = onSurface,
            surface = surface,
            onSurface = onSurface,
            surfaceVariant = containerHigh,
            onSurfaceVariant = onSurfaceVariant,
            surfaceTint = primary,
            inverseSurface = Color(0xFF313033),
            inverseOnSurface = Color(0xFFF4EFF4),
            outline = lerp(onSurfaceVariant, surface, 0.35f),
            outlineVariant = lerp(onSurfaceVariant, surface, 0.68f),
            scrim = Color.Black,
            surfaceBright = bright,
            surfaceDim = lerp(surface, Color.Black, 0.08f),
            surfaceContainerLowest = Color.White,
            surfaceContainerLow = low,
            surfaceContainer = container,
            surfaceContainerHigh = containerHigh,
            surfaceContainerHighest = containerHighest,
        )
    }
    return base
}

/**
 * AMOLED mode: true-black surfaces with the accent hue preserved. Used by the
 * keyboard so that OLED panels draw pure black between key caps.
 */
internal fun amoledify(scheme: ColorScheme): ColorScheme = scheme.copy(
    background = Color.Black,
    surface = Color.Black,
    surfaceDim = Color.Black,
    surfaceBright = Color(0xFF131313),
    surfaceContainerLowest = Color(0xFF000000),
    surfaceContainerLow = Color(0xFF0A0A0C),
    surfaceContainer = Color(0xFF101014),
    surfaceContainerHigh = Color(0xFF16161B),
    surfaceContainerHighest = Color(0xFF1D1D23),
    surfaceVariant = Color(0xFF1D1D23),
)

// ---------------------------------------------------------------------------
// Tonal maths (no HCT dependency, deterministic and allocation free)
// ---------------------------------------------------------------------------

private fun lighten(color: Color, by: Float): Color =
    lerp(color, Color.White, by.coerceIn(BLACK_TONE, WHITE_TONE))

private fun darken(color: Color, by: Float): Color =
    lerp(color, Color.Black, by.coerceIn(BLACK_TONE, WHITE_TONE))
