    fun lookup(romanInput: String): String? {
        if (romanInput.isEmpty()) return null
        val lower = romanInput.lowercase()
        EXACT_MAP[lower]?.let { return it }

        if (lower.length >= 3) {
            for ((suffix, devSuffix) in SUFFIX_RULES) {
                if (lower.length > suffix.length && lower.endsWith(suffix)) {
                    val stem = lower.substring(0, lower.length - suffix.length)
                    val baseDev = EXACT_MAP[stem]
                    if (baseDev != null) {
                        return baseDev + devSuffix
                    }
                }
            }
        }
        return null
    }
